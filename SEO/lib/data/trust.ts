export function getTrustConfigForPageType(pageType: PageType): TrustBlockConfig {
  const base = BASE_TRUST_CONFIG;
  const overrides = TRUST_BY_PAGE_TYPE[pageType];

  if (!overrides) {
    return base;
  }

  return {
    pageTypes: base.pageTypes,
    methodology: overrides.methodology ?? base.methodology,
    disclaimer: overrides.disclaimer ?? base.disclaimer,
    assumptions: overrides.assumptions ?? base.assumptions,
    limitations: overrides.limitations ?? base.limitations,
    lastUpdated: overrides.lastUpdated ?? base.lastUpdated
  };
}

