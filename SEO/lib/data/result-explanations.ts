import type { SeoRouteType } from "@/lib/seo/decisions";
import type { CalculationDirection } from "@/lib/calculations/types";

export interface ResultExplanation {
  title: string;
  bullets: string[];
}

export function getResultExplanation(options: {
  routeType: SeoRouteType;
  mode: CalculationDirection;
  hasComparison: boolean;
}): ResultExplanation {
  const baseTitle = "Как читать результат";

  if (options.routeType === "generic-calculator") {
    return {
      title: baseTitle,
      bullets: [
        "Net — это сумма «на руки» после вычета налогов и взносов; мы считаем её по типовым ставкам без индивидуальных льгот.",
        "Эффективная ставка показывает долю дохода, уходящую на налоги и взносы: по ней удобно сравнивать сценарии и страны.",
        "Отдельно мы оцениваем годовую сумму налогов и возможный налоговый возврат по вычетам (обучение, медицина, жильё/ипотека, благотворительность и др.): это ориентировочные цифры, которые зависят от страны и выбранной категории, не заменяют индивидуальную консультацию и не могут превышать фактически уплаченный налог.",
        "Затраты работодателя (employer cost) — это gross плюс взносы работодателя; они показывают полную стоимость позиции для компании.",
        options.hasComparison
          ? "Сохранённый сценарий можно использовать как отправную точку для сравнения с более детальными страницами по городам и профессиям."
          : "После базового расчёта можно перейти на страницы городов и профессий, чтобы уточнить картину для конкретного рынка."
      ]
    };
  }

  if (options.routeType === "gross-to-net") {
    return {
      title: baseTitle,
      bullets: [
        "Gross — сумма из оффера до налогов и взносов; Net — ориентировочная сумма «на руки» после стандартных удержаний.",
        "Эффективная ставка важна для сравнения: она показывает реальную налоговую нагрузку в процентах, а не только абсолютные цифры.",
        "Блок с годовыми налогами и оценкой налогового возврата показывает, сколько вы платите за год и какая часть может быть возвращена при наличии вычетов по выбранной категории; модель упрощена и учитывает только базовые лимиты по стране, поэтому результат остаётся приблизительной оценкой, а не обещанием возврата.",
        "Employer cost — полная стоимость для работодателя (gross + его взносы); полезна при сравнении офферов с разной структурой.",
        options.hasComparison
          ? "Сравнение сценариев условное: мы сопоставляем два расчёта при одних и тех же допущениях; в жизни итог может отличаться."
          : "Можно сохранить текущий сценарий и изменить параметры, чтобы сравнить варианты gross и понять, насколько чувствителен net."
      ]
    };
  }


  if (options.routeType === "net-to-gross") {
    return {
      title: baseTitle,
      bullets: [
        "Вы задаёте целевой net — калькулятор оценивает, какой gross нужен при типичных ставках; реальный оффер может отличаться.",
        "Эффективная ставка важна: по ней видно, какая доля дохода уходит на налоги и взносы при заданном net.",
        "Оценка возможного налогового возврата строится на указанной сумме вычетов и текущей налоговой нагрузке по выбранной категории и всегда ограничена величиной уплаченного за год налога и простыми лимитами по стране.",
        "Employer cost показывает, сколько в сумме обходится работодателю ваш целевой net — полезно для переговоров.",
        options.hasComparison
          ? "Сравнение условное: оба сценария считаются по одной методологии; сохраните несколько целей по net, чтобы увидеть диапазон gross."
          : "Можно сохранить результат как базовый сценарий, а затем попробовать другие значения net, чтобы очертить комфортный диапазон ожиданий."
      ]
    };
  }

  if (options.routeType === "profession-city") {
    return {
      title: baseTitle,
      bullets: [
        "Net — ориентировочная сумма «на руки» для этой профессии и города при типичных ставках; реальный доход может отличаться.",
        "Employer cost — полная стоимость позиции для работодателя (gross + взносы работодателя); полезна при сравнении офферов.",
        "Эффективная ставка важна для сравнения с другими городами и странами: по ней видна реальная налоговая нагрузка.",
        options.hasComparison
          ? "Сравнение сценариев условное: оба расчёта по одним допущениям; меняйте сумму или период, чтобы увидеть чувствительность net."
          : "Можно сохранить текущий сценарий, а затем сравнить его с другими вариантами (другая сумма, период или формат gross/net)."
      ]
    };
  }

  if (options.routeType === "city-comparison") {
    return {
      title: "Как читать сравнение городов",
      bullets: [
        "Net в каждой колонке — ориентировочная сумма «на руки» при одном и том же gross; разница обусловлена местными налогами и взносами.",
        "Employer cost — полная стоимость позиции для работодателя в этом городе; помогает сравнивать офферы с разной структурой.",
        "Эффективная ставка важна: по ней видно, где налоговая нагрузка выше, даже если номинальный gross одинаков.",
        "Сравнение условное: не учтены индивидуальные льготы, стоимость жизни и то, как один и тот же net ощущается в разных городах — используйте как ориентир."
      ]
    };
  }

  if (options.routeType === "profession-comparison") {
    return {
      title: "Как читать сравнение профессий",
      bullets: [
        "При одной стране и одном gross net и effective rate для двух профессий совпадают; различаются типичные рыночные вилки по ролям.",
        "Employer cost здесь одинаков при одном gross — он показывает полную стоимость позиции для работодателя.",
        "Эффективная ставка важна для сравнения с другими странами/городами; на этой странице контекст — типичные уровни дохода по профессиям.",
        "Сравнение условное: реальные офферы зависят от компании, уровня и локации — используйте как ориентир для обсуждения с рекрутером."
      ]
    };
  }

  return {
    title: baseTitle,
    bullets: [
      "Gross — это сумма до вычета налогов и взносов, Net — ориентировочная сумма «на руки» после стандартных удержаний.",
      "Эффективная ставка налога помогает сравнивать разные сценарии между собой, даже если суммы и периоды отличаются.",
      options.hasComparison
        ? "Блок сравнения сценариев показывает разницу между сохранённым и текущим вариантом и пригоден для печати или пересылки."
        : "Чтобы лучше понять чувствительность результата, сохраните один сценарий и измените параметры — сравнение поможет зафиксировать выводы."
    ]
  };
}

